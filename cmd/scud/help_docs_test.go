package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"

	"github.com/spf13/cobra"
)

var updateHelp = flag.Bool("update-help", false, "Regenerate docs/CLI_REFERENCE.md from Cobra help")

// Construct help only: never Execute, run hooks, contact providers, or open a project.
func helpRoot() *cobra.Command {
	root := newRoot()
	root.Version = "3.0.0" // Build-time version injection must not change the reference.
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	root.InitDefaultVersionFlag()
	return root
}

func walkHelp(c *cobra.Command, visit func(*cobra.Command)) {
	visit(c)
	for _, child := range c.Commands() {
		walkHelp(child, visit)
	}
}

func renderCLIReference(t *testing.T) []byte {
	t.Helper()
	var doc bytes.Buffer
	doc.WriteString("# Scud v3 CLI reference\n\n")
	doc.WriteString("Generated from `newRoot()` and Cobra help, including built-in help and completion commands.\n")
	doc.WriteString("Do not edit this file by hand. Regenerate from the repository root:\n\n")
	doc.WriteString("```sh\ngo test ./cmd/scud -run '^TestCLIReference$' -args -update-help\n```\n\n")
	root := helpRoot()
	walkHelp(root, func(c *cobra.Command) {
		fmt.Fprintf(&doc, "## `%s`\n\n```text\n", c.CommandPath())
		var out bytes.Buffer
		c.SetOut(&out)
		c.SetErr(&out)
		c.InitDefaultHelpFlag()
		if err := c.Help(); err != nil {
			t.Fatalf("%s help: %v", c.CommandPath(), err)
		}
		doc.WriteString(strings.TrimRight(out.String(), "\n"))
		doc.WriteString("\n```\n\n")
	})
	return append(bytes.TrimRight(doc.Bytes(), "\n"), '\n')
}

func TestCLIReference(t *testing.T) {
	want := renderCLIReference(t)
	path := filepath.Join("..", "..", "docs", "CLI_REFERENCE.md")
	if *updateHelp {
		if err := os.WriteFile(path, want, 0644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("CLI reference is stale; run go test ./cmd/scud -run '^TestCLIReference$' -args -update-help")
	}
	if again := renderCLIReference(t); !bytes.Equal(want, again) {
		t.Fatal("help generation is not deterministic")
	}
}

func TestCommandHelpCoverage(t *testing.T) {
	// Check real command descriptions, not Cobra's generated completion boilerplate.
	root := newRoot()
	flagPattern := regexp.MustCompile(`--[a-z][a-z-]*`)
	walkHelp(root, func(c *cobra.Command) {
		t.Run(c.CommandPath(), func(t *testing.T) {
			if strings.TrimSpace(c.Long) == "" || strings.TrimSpace(c.Example) == "" {
				t.Fatal("real commands must explain behavior and provide examples")
			}
			ownExample := false
			for _, line := range strings.Split(c.Example, "\n") {
				start := strings.Index(line, "scud ")
				if start < 0 {
					continue
				}
				invocation := line[start+len("scud "):]
				invocation = strings.SplitN(invocation, "|", 2)[0]
				invocation = strings.SplitN(invocation, ">", 2)[0]
				selected, _, err := root.Find(strings.Fields(invocation))
				if err != nil {
					t.Fatalf("unknown command in example %q: %v", line, err)
				}
				if selected == c || strings.HasPrefix(selected.CommandPath(), c.CommandPath()+" ") {
					ownExample = true
				}
				for _, name := range flagPattern.FindAllString(invocation, -1) {
					name = strings.TrimPrefix(name, "--")
					if selected.Flags().Lookup(name) == nil && selected.InheritedFlags().Lookup(name) == nil {
						t.Errorf("unknown flag --%s in %q", name, line)
					}
				}
			}
			if !ownExample {
				t.Error("no example invokes this command or a subcommand")
			}
		})
	})
}
